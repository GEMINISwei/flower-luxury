import { expect, test, type Page } from "@playwright/test"
import { admin, login, logout } from "./support"

async function createBrand(page: Page, name: string) {
  await page.goto("/brands")
  await page.getByRole("button", { name: "新增品牌", exact: true }).click()
  const dialog = page.getByRole("dialog")
  await dialog.getByLabel(/^名稱\*?$/).fill(name)
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
}

async function createProduct(page: Page, name: string, brand: string) {
  await page.goto("/products/new")
  await page.getByLabel(/^名稱\*?$/).fill(name)
  await page.getByRole("combobox", { name: /^品牌\*?$/ }).selectOption({ label: brand })
  await page.getByRole("combobox", { name: /^分類\*?$/ }).selectOption("包包")
  await page.getByLabel("型號", { exact: true }).fill("Model 3")
  await page.getByLabel("序號", { exact: true }).fill("SERIAL3")
  await page.getByLabel("顏色", { exact: true }).fill("black")
  await page.getByLabel("年份", { exact: true }).fill("2026")
  await page.getByLabel(/^成本（新臺幣）\*?$/).fill("3000")
  await page.getByLabel("備註", { exact: true }).fill("Original note")
  await page.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(page).toHaveURL(/\/products\/[0-9a-f-]+$/)
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible()
}

test("商品核心可建檔編輯篩選並刪除後回列表", async ({ page }) => {
  await login(page, admin)
  await createBrand(page, "Phase3 Brand")
  await createProduct(page, "Phase3 Bag", "Phase3 Brand")
  const detailUrl = page.url()
  await expect(page.getByText(/^LX\d{8}[A-Z0-9]{5}$/).first()).toBeVisible()
  await expect(page.getByRole("heading", { name: "流向記錄", exact: true })).toHaveCount(0)
  await expect(page.getByText("每筆詢價自行填寫匯率，未提供時預設為 1。", { exact: true }))
    .toHaveCount(0)
  await page.locator("header").getByRole("button", { name: "查看商品歷程", exact: true }).click()
  await expect(page).toHaveURL(`${detailUrl}/history`)
  await expect(page.getByRole("heading", { name: "流向記錄", exact: true })).toBeVisible()
  await expect(page.getByText("尚無成交紀錄", { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole("heading", { name: "商品歷程", exact: true })).toBeVisible()
  await page.getByRole("link", { name: "返回商品詳情", exact: true }).click()
  await page.getByRole("button", { name: "編輯商品", exact: true }).click()
  let dialog = page.getByRole("dialog", { name: "編輯商品", exact: true })
  await dialog.getByLabel(/^名稱\*?$/).fill("Phase3 Bag Updated")
  await dialog.getByLabel("備註", { exact: true }).fill("Updated note")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole("heading", { name: "Phase3 Bag Updated", exact: true })).toBeVisible()
  await page.goto("/products")
  await page.locator("header").getByRole("button", { name: "操作選單", exact: true }).click()
  await page.getByRole("menuitem", { name: "篩選", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "搜尋", exact: true })
  await dialog.getByLabel("名稱、SKU 或序號", { exact: true }).fill("SERIAL3")
  await dialog.getByRole("button", { name: "篩選", exact: true }).click()
  await expect(page).toHaveURL(/keyword=SERIAL3/)
  await page.getByRole("link").filter({ hasText: "Phase3 Bag Updated" }).click()
  await page.getByRole("button", { name: "刪除商品", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "刪除商品", exact: true })
  await dialog.getByRole("button", { name: "取消", exact: true }).click()
  await expect(page).toHaveURL(detailUrl)
  await page.getByRole("button", { name: "刪除商品", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "刪除商品", exact: true }).click()
  await expect(page).toHaveURL("/products")
  await expect(page.getByRole("link").filter({ hasText: "Phase3 Bag Updated" })).toHaveCount(0)
  await page.goto(detailUrl)
  await expect(page.getByRole("heading", { name: "找不到頁面", exact: true })).toBeVisible()
  await page.goto(`${detailUrl}/history`)
  await expect(page.getByRole("heading", { name: "找不到頁面", exact: true })).toBeVisible()
})

test("員工共用商品且停用品牌仍可保留於原商品", async ({ page }) => {
  await login(page, admin)
  await createBrand(page, "Phase3 Shared")
  await createProduct(page, "Phase3 Shared Bag", "Phase3 Shared")
  const detailUrl = page.url()
  await page.goto("/brands")
  const row = page.getByRole("row").filter({ hasText: "Phase3 Shared" })
  await expect(row.getByRole("button", { name: "停用", exact: true })).toHaveCount(0)
  await expect(row.getByRole("button", { name: "刪除", exact: true })).toHaveCount(0)
  await row.getByRole("button", { name: "編輯", exact: true }).click()
  await page.getByRole("dialog").getByRole("combobox", { name: "狀態", exact: true })
    .selectOption("false")
  await page.getByRole("dialog").getByRole("button", { name: "儲存", exact: true }).click()
  await expect(page.getByRole("dialog")).toBeHidden()
  await expect(row.getByRole("cell", { name: "停用", exact: true })).toBeVisible()
  await page.goto("/admin/users")
  await page.getByRole("button", { name: "新增員工", exact: true }).click()
  let dialog = page.getByRole("dialog")
  await dialog.getByLabel("暱稱").fill("商品員工")
  await dialog.getByLabel("帳號").fill("product-staff")
  await dialog.getByLabel(/^密碼\*?$/).fill("product-staff-password")
  await dialog.getByRole("button", { name: "建立", exact: true }).click()
  await expect(dialog).toBeHidden()
  await logout(page)
  await login(page, { username: "product-staff", password: "product-staff-password" })
  await page.goto(detailUrl)
  await page.getByRole("button", { name: "編輯商品", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "編輯商品", exact: true })
  await expect(dialog.getByRole("option", { name: "Phase3 Shared", exact: true })).toHaveCount(1)
  await dialog.getByLabel(/^名稱\*?$/).fill("Phase3 Shared Edited")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole("heading", { name: "Phase3 Shared Edited", exact: true })).toBeVisible()
  await page.goto("/products/new")
  await expect(page.getByRole("option", { name: "Phase3 Shared", exact: true })).toHaveCount(0)
})

test("手機商品列表提供卡片篩選與更多設定入口", async ({ page }) => {
  await login(page, admin)
  await createBrand(page, "Phase3 Mobile")
  await createProduct(page, "Phase3 Mobile Item", "Phase3 Mobile")
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/products")
  const nav = page.getByRole("navigation", { name: "手機主要導覽", exact: true })
  await expect(nav.getByRole("link", { name: "商品", exact: true })).toBeVisible()
  await expect(page.getByRole("link").filter({ hasText: "Phase3 Mobile Item" })).toBeVisible()
  await page.locator("header").getByRole("button", { name: "操作選單", exact: true }).click()
  await page.getByRole("menuitem", { name: "篩選", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "搜尋", exact: true })
  await dialog.getByLabel("名稱、SKU 或序號", { exact: true }).fill("Phase3 Mobile")
  await dialog.getByRole("button", { name: "篩選", exact: true }).click()
  await expect(page.getByRole("link").filter({ hasText: "Phase3 Mobile Item" })).toBeVisible()
  await nav.getByRole("button", { name: "更多", exact: true }).click()
  const more = page.getByRole("dialog", { name: "更多", exact: true })
  await expect(more.getByRole("button", { name: "用戶設定", exact: true })).toBeVisible()
  await more.getByRole("button", { name: "用戶設定", exact: true }).click()
  await expect(page).toHaveURL("/settings")
})


test("商品歷程可直接開啟且不存在商品顯示找不到頁面", async ({ page }) => {
  await login(page, admin)
  for (const id of ["not-a-product-id", "00000000-0000-4000-8000-000000000000"]) {
    await page.goto(`/products/${id}/history`)
    await expect(page.getByRole("heading", { name: "找不到頁面", exact: true })).toBeVisible()
  }
})
