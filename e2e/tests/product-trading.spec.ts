import { expect, test, type Page } from "@playwright/test"
import { admin, login } from "./support"

async function prepareTrade(page: Page, name: string) {
  await login(page, admin)
  await page.goto("/vendors")
  await page.getByRole("button", { name: "新增廠商", exact: true }).click()
  let dialog = page.getByRole("dialog")
  await dialog.getByLabel(/^名稱\*?$/).fill(name)
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto("/brands")
  await page.getByRole("button", { name: "新增品牌", exact: true }).click()
  dialog = page.getByRole("dialog")
  await dialog.getByLabel(/^名稱\*?$/).fill(name)
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto("/products/new")
  await page.getByLabel(/^名稱\*?$/).fill(name)
  await page.getByRole("combobox", { name: /^品牌\*?$/ }).selectOption({ label: name })
  await page.getByRole("combobox", { name: /^分類\*?$/ }).selectOption("包包")
  await page.getByLabel(/^成本（新臺幣）\*?$/).fill("3000")
  await page.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(page).toHaveURL(/\/products\/[0-9a-f-]+$/)
}

async function addQuote(page: Page, vendor: string, amount: string, rate = "1") {
  await page.getByRole("button", { name: "新增詢價", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "新增詢價", exact: true })
  await dialog.getByRole("combobox", { name: /^廠商\*?$/ }).selectOption({ label: vendor })
  await dialog.getByLabel(/^報價\*?$/).fill(amount)
  await expect(dialog.getByLabel(/^匯率\*?$/)).toHaveValue("1")
  await dialog.getByLabel(/^匯率\*?$/).fill(rate)
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
}

test("詢價逐筆修改匯率且成交退回再成交保留快照", async ({ page }) => {
  await prepareTrade(page, "Phase5 CNY")
  const detail = page.url()
  await page.goto(detail)
  await addQuote(page, "Phase5 CNY", "100", "4.5")
  await page.goto("/vendors")
  const row = page.getByRole("row").filter({ hasText: "Phase5 CNY" })
  await expect(row.getByRole("button", { name: "停用", exact: true })).toHaveCount(0)
  await expect(row.getByRole("button", { name: "刪除", exact: true })).toHaveCount(0)
  await row.getByRole("button", { name: "編輯", exact: true }).click()
  let dialog = page.getByRole("dialog")
  await dialog.getByRole("combobox", { name: "狀態", exact: true }).selectOption("false")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row.getByRole("cell", { name: "停用", exact: true })).toBeVisible()
  await row.getByRole("button", { name: "編輯", exact: true }).click()
  dialog = page.getByRole("dialog")
  await dialog.getByRole("combobox", { name: "狀態", exact: true }).selectOption("true")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto(detail)
  await page.getByRole("button", { name: "編輯", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "詢價", exact: true })
  await dialog.getByLabel(/^報價\*?$/).fill("200")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText("TWD 900", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "編輯", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "詢價", exact: true })
  await expect(dialog.getByLabel(/^匯率\*?$/)).toHaveValue("4.5")
  await dialog.getByLabel(/^匯率\*?$/).fill("5")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText("TWD 1,000", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "確認成交", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "確認成交", exact: true })
  await expect(dialog).toContainText("此筆成交將虧損 2,000 TWD。")
  await dialog.getByRole("button", { name: "取消", exact: true }).click()
  await expect(page.getByRole("button", { name: "編輯商品", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "確認成交", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "確認成交", exact: true })
  await dialog.getByRole("button", { name: "確認成交", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole("button", { name: "編輯商品", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "新增詢價", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "退回狀態", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "退回狀態", exact: true })
  await dialog.getByLabel(/^退回原因（必填）\*?$/).fill("   ")
  await dialog.getByRole("button", { name: "退回狀態", exact: true }).click()
  await expect(dialog.getByRole("alert")).toHaveText("此欄位為必填")
  await dialog.getByLabel(/^退回原因（必填）\*?$/).fill("Phase5 returned")
  await dialog.getByRole("button", { name: "退回狀態", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText("Phase5 returned", { exact: true })).toHaveCount(0)
  await expect(page.getByText("目前成交詢價", { exact: true })).toHaveCount(0)
  await page.locator("header").getByRole("button", { name: "查看商品歷程", exact: true }).click()
  await expect(page.getByText("Phase5 returned", { exact: true })).toHaveCount(2)
  await page.getByRole("link", { name: "返回商品詳情", exact: true }).click()
  await expect(page.getByRole("button", { name: "刪除詢價", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "編輯商品", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "編輯商品", exact: true })
  await dialog.getByLabel(/^成本（新臺幣）\*?$/).fill("10")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto("/vendors")
  await page.getByRole("button", { name: "新增廠商", exact: true }).click()
  dialog = page.getByRole("dialog")
  await dialog.getByLabel(/^名稱\*?$/).fill("Phase5 second vendor")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto(detail)
  await addQuote(page, "Phase5 second vendor", "1000")
  await page.getByRole("region", { name: "Phase5 second vendor", exact: true })
    .getByRole("button", { name: "確認成交", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "確認成交", exact: true })
  await dialog.getByRole("button", { name: "確認成交", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText("目前成交詢價", { exact: true })).toHaveCount(1)
  await expect(page.getByRole("region", { name: "目前成交", exact: true })).toHaveCount(0)
  const current = page.getByRole("region", { name: "Phase5 second vendor", exact: true })
  const other = page.getByRole("region", { name: "Phase5 CNY", exact: true })
  const border = (element: HTMLElement) => Number.parseFloat(getComputedStyle(element).borderTopWidth)
  expect(await current.evaluate(border)).toBeGreaterThan(await other.evaluate(border))
  expect(await current.evaluate((element) => getComputedStyle(element).backgroundColor))
    .not.toBe(await other.evaluate((element) => getComputedStyle(element).backgroundColor))
  await expect(page.getByRole("region", { name: "Phase5 second vendor", exact: true })
    .getByText("目前成交詢價", { exact: true })).toBeVisible()
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    const badge = await current.getByText("目前成交詢價", { exact: true }).boundingBox()
    const card = await current.boundingBox()
    expect(badge!.width).toBeLessThan(card!.width * 0.75)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await expect(page.locator("header")
      .getByRole("button", { name: "查看商品歷程", exact: true })).toBeVisible()
  }
  await expect(page.getByRole("heading", { name: "成交歷史", exact: true })).toHaveCount(0)
  await page.locator("header").getByRole("button", { name: "查看商品歷程", exact: true }).click()
  await expect(page.getByRole("heading", { name: "成交歷史", exact: true })).toBeVisible()
  await expect(page.getByText("目前成交", { exact: true })).toBeVisible()
  await expect(page.getByText("已退回", { exact: true })).toBeVisible()
  await expect(page.getByText("-2,000", { exact: true })).toBeVisible()
  await expect(page.getByText("990", { exact: true })).toBeVisible()
})

test("詢價驗證匯率且未成交詢價可取消刪除", async ({ page }) => {
  await prepareTrade(page, "Phase5 TWD")
  await page.getByRole("button", { name: "新增詢價", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "新增詢價", exact: true })
  await dialog.getByRole("combobox", { name: /^廠商\*?$/ }).selectOption({ label: "Phase5 TWD" })
  await dialog.getByLabel(/^報價\*?$/).fill("1.01")
  await dialog.getByLabel(/^匯率\*?$/).fill("0")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog.getByRole("alert")).toHaveText("請輸入大於 0 且最多六位小數的匯率")
  await dialog.getByLabel(/^報價\*?$/).fill("100")
  await dialog.getByLabel(/^匯率\*?$/).fill("1")
  await dialog.getByRole("button", { name: "儲存", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText("TWD 100", { exact: true }).first()).toBeVisible()
  await expect(page.getByRole("button", { name: "套用最新匯率", exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "刪除詢價", exact: true }).click()
  let confirm = page.getByRole("dialog", { name: "刪除詢價", exact: true })
  await confirm.getByRole("button", { name: "取消", exact: true }).click()
  await expect(page.getByText("TWD 100", { exact: true }).first()).toBeVisible()
  await page.getByRole("button", { name: "刪除詢價", exact: true }).click()
  confirm = page.getByRole("dialog", { name: "刪除詢價", exact: true })
  await confirm.getByRole("button", { name: "刪除詢價", exact: true }).click()
  await expect(confirm).toBeHidden()
  await expect(page.getByText("尚無詢價。請先新增廠商報價，再確認成交。", { exact: true })).toBeVisible()
})
