import { expect, test } from "@playwright/test"
import { admin, login } from "./support"

test("用戶設定與系統設定各自顯示所屬內容", async ({ page }) => {
  await login(page, admin)
  await page.getByRole("button", { name: "帳號選單", exact: true }).click()
  await page.getByRole("menuitem", { name: "用戶設定", exact: true }).click()
  await expect(page).toHaveURL("/settings")
  await expect(page.getByRole("heading", { name: "用戶設定", exact: true })).toBeVisible()
  await expect(page.getByRole("heading", { name: "個人資料", exact: true })).toBeVisible()
  await expect(page.getByRole("heading", { name: "更改密碼", exact: true })).toBeVisible()
  await expect(page.getByLabel("暱稱", { exact: true })).toBeVisible()
  await expect(page.getByLabel("目前密碼", { exact: true })).toBeVisible()
  await expect(page.getByLabel("新密碼", { exact: true })).toBeVisible()
  await expect(page.getByLabel("確認新密碼", { exact: true })).toBeVisible()
  await expect(page.getByRole("combobox", { name: "顯示語言", exact: true })).toHaveCount(0)
  await expect(page.getByText("系統版本", { exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: "帳號選單", exact: true }).click()
  await page.getByRole("menuitem", { name: "系統設定", exact: true }).click()
  await expect(page).toHaveURL("/settings/system")
  await expect(page.getByRole("heading", { name: "系統設定", exact: true })).toBeVisible()
  await expect(page.getByRole("combobox", { name: "顯示語言", exact: true })).toBeVisible()
  await expect(page.getByText("系統版本", { exact: true })).toBeVisible()
  await expect(page.getByText("無法取得", { exact: true })).toHaveCount(0)
  await expect(page.getByLabel("暱稱", { exact: true })).toHaveCount(0)
  await expect(page.getByLabel("目前密碼", { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole("heading", { name: "系統設定", exact: true })).toBeVisible()
})
